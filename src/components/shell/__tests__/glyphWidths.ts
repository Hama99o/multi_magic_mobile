/** Width in dp of `text` at `fontSize`, by the table (unknown glyphs count as "W"). */
export function textWidth(text: string, fontSize: number): number {
  let em = 0;
  for (const c of text) em += GLYPH_EM[c] ?? GLYPH_EM.W;
  return em * fontSize;
}
